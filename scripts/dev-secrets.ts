/**
 * Writes the local dev secrets: `.env` (every service's tokens, caller hashes, database and Valkey users),
 * `deploy/.dev/valkey-users.acl`, the session signing key `deploy/.dev/session-ed25519.pem` (accounts reads it;
 * edge gets only the public key), audit's head signing key `deploy/.dev/audit-signing-key.pem` and connections'
 * master key `deploy/.dev/connections-master.key`. All are gitignored. Run once: `make dev-secrets` (it refuses to
 * overwrite unless you pass --force). `--example` prints `.env.example` instead (names only, no values).
 */
import { createHash, generateKeyPairSync, randomBytes } from 'node:crypto';
import { chmodSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DATA_SERVICES, PORTS, SERVICES, callGraph, valkeyAclRule, valkeyUser } from '@app/contracts';
import { envKey, hashToken } from '@app/service-kit';

const root = join(import.meta.dirname, '..');
const example = process.argv.includes('--example');
const force = process.argv.includes('--force');
const secret = () => (example ? '' : randomBytes(24).toString('base64url'));
const lines: string[] = ['# Generated by scripts/dev-secrets.ts. Local dev only. Never commit .env.', ''];
const put = (k: string, v: string) => lines.push(`${k}=${v}`);

// Service tokens: one per caller -> callee pair, from every endpoint's `callers` (plus runner -> sandbox-manager).
const graph = callGraph();
graph.runner = [...(graph.runner ?? []), 'sandbox-manager' as never];
const callers: Record<string, string[]> = {};
lines.push('# --- service tokens: <CALLER>_TOKEN_<CALLEE>, and the callee keeps only the hash in <CALLEE>_CALLERS');
for (const [caller, callees] of Object.entries(graph)) {
  if (caller === 'browser' || caller === 'public') continue;
  for (const callee of callees) {
    const t = secret();
    put(envKey(caller, `TOKEN_${callee.toUpperCase().replace(/-/g, '_')}`), t);
    (callers[callee] ??= []).push(`${caller}:${example ? '<sha256>' : hashToken(t)}`);
  }
}
for (const [callee, list] of Object.entries(callers)) put(envKey(callee, 'CALLERS'), list.join(','));

lines.push('', '# --- Postgres (deploy/compose.dev.yml, deploy/db-init.sql)');
put('PG_SUPERUSER_PASSWORD', secret());
for (const s of DATA_SERVICES) {
  const pw = secret();
  put(`DB_PASSWORD_${s.toUpperCase()}`, pw);
  put(envKey(s, 'DATABASE_URL'), `postgres://svc_${s}:${pw}@127.0.0.1:55432/app`);
}

lines.push('', '# --- Valkey: one ACL user per service');
const health = secret();
put('VALKEY_HEALTH_PASSWORD', health);
const acl = ['user default off', `user health on >${health} resetkeys -@all +ping`];
for (const s of SERVICES) {
  const pw = secret();
  put(envKey(s, 'VALKEY_URL'), `redis://${valkeyUser(s)}:${pw}@127.0.0.1:56379`);
  acl.push(`user ${valkeyUser(s)} on >${pw} ${valkeyAclRule(s)}`);
}

lines.push('', '# --- models: Vultr Serverless Inference. The key lives in its own file (one line, mode 600), never in .env.');
lines.push('# Blank = the default: key file /run/secrets/vultr-inference, caps $5/day global, $0.25 and 200000 tokens per account, 30 calls/min.');
put('MODELS_VULTR_KEY_FILE', example ? '' : (process.env.MODELS_VULTR_KEY_FILE ?? ''));
for (const k of ['DAILY_CAP_USD', 'ACCOUNT_DAILY_USD', 'ACCOUNT_DAILY_TOKENS', 'ACCOUNT_RPM', 'KILL', 'KEY_FINGERPRINTS']) put(envKey('models', k), '');

lines.push(
  '',
  '# --- markets: cache times in seconds (the defaults are shown) and where it reads the Brave key. The key itself never goes here.',
  '# MARKETS_QUOTE_TTL_S=15        (10-30)',
  '# MARKETS_LIST_TTL_S=30',
  '# MARKETS_HISTORY_TTL_S=60',
  '# MARKETS_FEED_TTL_S=600',
  '# MARKETS_SEARCH_TTL_S=1800     (one Brave search per game per 30 min, shared by every follower)',
  '# MARKETS_FEED_MAX_AGE_H=96',
  '# MARKETS_SOURCE_ENV=prod       (fixture: read the fixture rows of the source catalog instead)',
  '# MARKETS_BRAVE_KEY_FILE=      (an absolute path; the default is ~/.config/siren/secrets/brave-search)',
);

lines.push('', '# --- sessions: Ed25519. The private key file is accounts\' only; edge gets the public key (comma list during a rotation)');
const sessionKeyPath = join(root, 'deploy/.dev/session-ed25519.pem');
const session = generateKeyPairSync('ed25519');
const sessionPub = session.publicKey.export({ format: 'jwk' }).x as string;
put('ACCOUNTS_SESSION_KEY_FILE', example ? '' : sessionKeyPath);
put('EDGE_SESSION_PUBLIC_KEYS', example ? '' : sessionPub);
lines.push(`# kid ${example ? '<kid>' : createHash('sha256').update(Buffer.from(sessionPub, 'base64url')).digest('base64url').slice(0, 16)}`);
put('EDGE_ALLOWED_ORIGINS', 'http://localhost:5173,http://127.0.0.1:8080,http://localhost:8080');

lines.push('', '# --- audit: its Ed25519 signing key (a file only audit reads) and the write-once folder for signed heads (dev).');
lines.push('# Blank = the default: /run/secrets/audit-signing-key and /var/lib/audit/heads (Object Storage replaces the folder in Phase 3).');
const auditKeyPath = join(root, 'deploy/.dev/audit-signing-key.pem');
put(envKey('audit', 'SIGNING_KEY_FILE'), example ? '' : auditKeyPath);
put(envKey('audit', 'HEADS_DIR'), example ? '' : join(root, 'deploy/.dev/audit-heads'));

lines.push('', '# --- connections: the master key (32 bytes, base64) in its own file, mounted only by connections. Dev: deploy/.dev/.');
lines.push('# KALSHI_ENVS: blank = demo only (the public-demo default); "demo,prod" lets a real read-only key connect.');
const masterPath = join(root, 'deploy/.dev/connections-master.key');
put(envKey('connections', 'MASTER_KEY_FILE'), example ? '' : masterPath);
for (const k of ['KALSHI_ENVS', 'REFRESH_EVERY_S']) put(envKey('connections', k), '');

lines.push('', '# --- run a service as its in-memory fake: <SVC>_FAKE=1 (npm run fake -w services/<svc> sets it)');
lines.push(`# ports: ${Object.entries(PORTS).map(([k, v]) => `${k} ${v}`).join(', ')}`);
lines.push('# board keeps screenshots in BOARD_SCREENSHOT_DIR until Object Storage exists (default .data/board/screenshots)');
lines.push('LOG_LEVEL=info', '');

if (example) {
  process.stdout.write(lines.join('\n').replace(/<sha256>/g, '<sha256 of the caller token>'));
} else {
  const envPath = join(root, '.env');
  if (existsSync(envPath) && !force) {
    console.error('.env exists; pass --force to replace it (every token changes).');
    process.exit(1);
  }
  writeFileSync(envPath, lines.join('\n'), { mode: 0o600 });
  mkdirSync(join(root, 'deploy/.dev'), { recursive: true });
  const aclPath = join(root, 'deploy/.dev/valkey-users.acl');
  writeFileSync(aclPath, acl.join('\n') + '\n');
  chmodSync(aclPath, 0o644); // the valkey user in the container must read it
  writeFileSync(sessionKeyPath, session.privateKey.export({ format: 'pem', type: 'pkcs8' }) as string, { mode: 0o600 });
  chmodSync(sessionKeyPath, 0o600); // accounts refuses a key file others can read
  // audit's head signatures must stay checkable, so --force keeps an existing key.
  if (!existsSync(auditKeyPath)) {
    writeFileSync(auditKeyPath, generateKeyPairSync('ed25519').privateKey.export({ format: 'pem', type: 'pkcs8' }) as string, { mode: 0o600 });
  }
  // Kept across --force: a new master key would make every stored dev key unreadable. Delete the file to rotate it.
  if (!existsSync(masterPath)) writeFileSync(masterPath, randomBytes(32).toString('base64') + '\n', { mode: 0o600 });
  chmodSync(masterPath, 0o600);
  console.log('wrote .env and deploy/.dev/: valkey-users.acl, session-ed25519.pem, audit-signing-key.pem, connections-master.key');
}
