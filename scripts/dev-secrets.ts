/**
 * Writes the local dev secrets: `.env` (every service's tokens, caller hashes, database and Valkey users) and
 * `deploy/.dev/valkey-users.acl`. Both are gitignored. Run once: `make dev-secrets` (it refuses to overwrite
 * unless you pass --force). `--example` prints `.env.example` instead (names only, no values).
 */
import { randomBytes } from 'node:crypto';
import { chmodSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DATA_SERVICES, PORTS, SERVICES, callGraph, valkeyAclRule, valkeyUser } from '@app/contracts';
import { envKey, hashToken } from '@app/service-kit';

const root = join(import.meta.dirname, '..');
const example = process.argv.includes('--example');
const force = process.argv.includes('--force');
const secret = () => (example ? '' : randomBytes(24).toString('base64url'));
const lines: string[] = ['# Generated by scripts/dev-secrets.ts. Local dev only. Never commit .env.', ''];
const put = (k: string, v: string) => lines.push(`${k}=${v}`);

// Service tokens: one per caller -> callee pair, from every endpoint's `callers` (plus runner -> sandbox-manager).
const graph = callGraph();
graph.runner = [...(graph.runner ?? []), 'sandbox-manager' as never];
const callers: Record<string, string[]> = {};
lines.push('# --- service tokens: <CALLER>_TOKEN_<CALLEE>, and the callee keeps only the hash in <CALLEE>_CALLERS');
for (const [caller, callees] of Object.entries(graph)) {
  if (caller === 'browser' || caller === 'public') continue;
  for (const callee of callees) {
    const t = secret();
    put(envKey(caller, `TOKEN_${callee.toUpperCase().replace(/-/g, '_')}`), t);
    (callers[callee] ??= []).push(`${caller}:${example ? '<sha256>' : hashToken(t)}`);
  }
}
for (const [callee, list] of Object.entries(callers)) put(envKey(callee, 'CALLERS'), list.join(','));

lines.push('', '# --- Postgres (deploy/compose.dev.yml, deploy/db-init.sql)');
put('PG_SUPERUSER_PASSWORD', secret());
for (const s of DATA_SERVICES) {
  const pw = secret();
  put(`DB_PASSWORD_${s.toUpperCase()}`, pw);
  put(envKey(s, 'DATABASE_URL'), `postgres://svc_${s}:${pw}@127.0.0.1:55432/app`);
}

lines.push('', '# --- Valkey: one ACL user per service');
const health = secret();
put('VALKEY_HEALTH_PASSWORD', health);
const acl = ['user default off', `user health on >${health} resetkeys -@all +ping`];
for (const s of SERVICES) {
  const pw = secret();
  put(envKey(s, 'VALKEY_URL'), `redis://${valkeyUser(s)}:${pw}@127.0.0.1:56379`);
  acl.push(`user ${valkeyUser(s)} on >${pw} ${valkeyAclRule(s)}`);
}

lines.push('', '# --- run a service as its in-memory fake: <SVC>_FAKE=1 (npm run fake -w services/<svc> sets it)');
lines.push(`# ports: ${Object.entries(PORTS).map(([k, v]) => `${k} ${v}`).join(', ')}`);
lines.push('LOG_LEVEL=info', '');

if (example) {
  process.stdout.write(lines.join('\n').replace(/<sha256>/g, '<sha256 of the caller token>'));
} else {
  const envPath = join(root, '.env');
  if (existsSync(envPath) && !force) {
    console.error('.env exists; pass --force to replace it (every token changes).');
    process.exit(1);
  }
  writeFileSync(envPath, lines.join('\n'), { mode: 0o600 });
  mkdirSync(join(root, 'deploy/.dev'), { recursive: true });
  const aclPath = join(root, 'deploy/.dev/valkey-users.acl');
  writeFileSync(aclPath, acl.join('\n') + '\n');
  chmodSync(aclPath, 0o644); // the valkey user in the container must read it
  console.log('wrote .env and deploy/.dev/valkey-users.acl');
}
