/**
 * Regenerates everything derived in packages/contracts:
 *  - schema/rust/{engine,sandbox-manager}.json from `engine --schema` and `sandbox-manager --schema`
 *  - src/generated/{engine,sandbox-manager}.ts from those (json-schema-to-typescript)
 *  - schema/ts/*.json: JSON Schema of every zod schema (for readers and non-TS tools)
 * `--check` fails (exit 1) if anything on disk differs, without writing.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, '..');
const root = join(pkg, '..', '..');
const check = process.argv.includes('--check');
const stale: string[] = [];

function put(path: string, content: string) {
  const old = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (old === content) return;
  if (check) {
    stale.push(path.replace(root + '/', ''));
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log('wrote', path.replace(root + '/', ''));
}

function cargoSchema(pkgName: string): unknown {
  const out = execFileSync('cargo', ['run', '-q', '-p', pkgName, '--', '--schema'], { cwd: root, encoding: 'utf8' });
  return JSON.parse(out);
}

const header = '/* Generated by packages/contracts/scripts/gen.ts from the Rust crate\'s --schema. Do not edit. */\n';

async function typesFor(defs: Record<string, unknown>, sharedDefs: Record<string, unknown>): Promise<string> {
  // One TS module with an exported type per named schema; shared $defs become types once.
  const all: Record<string, unknown> = { ...sharedDefs };
  for (const [name, s] of Object.entries(defs)) {
    const { $defs, ...rest } = s as { $defs?: Record<string, unknown> };
    Object.assign(all, $defs ?? {});
    all[name] = rest;
  }
  const rootSchema = {
    title: '__Root',
    type: 'object',
    properties: Object.fromEntries(Object.keys(all).map((k) => [k, { $ref: `#/$defs/${k}` }])),
    $defs: all,
  };
  const ts = await compile(rootSchema as never, '__Root', {
    bannerComment: '',
    additionalProperties: false,
    unreachableDefinitions: true,
    style: { singleQuote: true },
  });
  return header + ts.replace(/export interface __Root \{[\s\S]*?\n\}\n/, '');
}

const engine = cargoSchema('engine') as Record<string, unknown>;
const manager = cargoSchema('sandbox-manager') as { schemas: Record<string, unknown> };
put(join(pkg, 'schema/rust/engine.json'), JSON.stringify(engine, null, 2) + '\n');
put(join(pkg, 'schema/rust/sandbox-manager.json'), JSON.stringify(manager, null, 2) + '\n');

const engineNamed = {
  Plan: engine.plan,
  EngineInput: engine.input,
  EngineResult: engine.result,
  Receipt: engine.receipt,
};
put(join(pkg, 'src/generated/engine.ts'), await typesFor(engineNamed, {}));
put(join(pkg, 'src/generated/sandbox-manager.ts'), await typesFor(manager.schemas, {}));

// JSON Schema of the TS-owned schemas (import after the Rust files exist).
const c = await import('../src/index.ts');
const { z } = await import('zod');
const tsSchemas: Record<string, unknown> = {};
const named: Record<string, unknown> = {
  Look: c.Look,
  WidgetSpec: c.WidgetSpec,
  WidgetDraft: c.WidgetDraft,
  WidgetProfile: c.WidgetProfile,
  WidgetCatalog: c.WidgetCatalog,
  SourceCatalog: c.SourceCatalog,
  Candidate: c.Candidate,
  Verdict: c.Verdict,
  WidgetResult: c.WidgetResult,
  SlotSummary: c.SlotSummary,
  RunTraceStep: c.RunTraceStep,
  LogEntry: c.LogEntry,
  WidgetRunJob: c.WidgetRunJob,
  AccountRefreshJob: c.AccountRefreshJob,
  SessionClaims: c.SessionClaims,
};
for (const [n, s] of Object.entries(named)) tsSchemas[n] = z.toJSONSchema(s as never, { unrepresentable: 'any' });
for (const [e, d] of Object.entries(c.EVENTS)) tsSchemas[`event:${e}`] = z.toJSONSchema(d.schema as never, { unrepresentable: 'any' });
for (const [tool, s] of Object.entries(c.AGENT_TOOLS)) tsSchemas[`tool:${tool}`] = z.toJSONSchema(s as never, { unrepresentable: 'any' });
put(join(pkg, 'schema/ts/schemas.json'), JSON.stringify(tsSchemas, null, 2) + '\n');

const endpoints = Object.values(c.APIS).flatMap((t) =>
  Object.values(t as Record<string, import('../src/endpoint.ts').Endpoint>).map((e) => ({
    service: e.service,
    name: e.name,
    method: e.method,
    path: e.path,
    callers: e.callers,
    status: e.status,
    errors: e.errors,
    summary: e.summary,
  })),
);
put(join(pkg, 'schema/ts/endpoints.json'), JSON.stringify(endpoints, null, 2) + '\n');

if (check && stale.length) {
  console.error('Generated contract files are stale. Run `npm run gen` and commit:\n  ' + stale.join('\n  '));
  process.exit(1);
}
